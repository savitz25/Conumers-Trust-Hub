// Builds the candidate half of the exact-USDOT binding expansion packet from
// the Move enumeration (move repo: scripts/qa/mth-exact-usdot-candidates.ts).
// Pure file transform: reads one JSON file, writes the candidate SQL and the
// row-level Move evidence CSV. It contacts no database and no network.
//
//   node scripts/release/mth-v2-exact-usdot-packet.mjs <move-candidates.json> [<out dir>]
// The enumeration behind the shipped files is kept in the Move repo:
//   docs/my-trusthub-v2-production/exact-usdot-enumeration-2026-10-03.json
//
// Deterministic: the same enumeration always yields byte-identical output.
// Identity is the USDOT number only. The legal name is a label; it is used
// solely to HOLD BACK candidates whose label collides (packet 10 refuses an
// existing Move entity with the same canonical name), never to connect any.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const USDOT = /^[1-9][0-9]{0,8}$/, SLUG = /^[a-z0-9][a-z0-9-]{0,159}$/;
const MOVE_PROJECT = 'arepfylnilkjmyduhwbz';

/** Move-side verdict for every PUBLISHABLE row; `candidates` are the exact-USDOT rows handed to Ask. */
export function buildManifest(enumeration) {
  if (enumeration.project !== MOVE_PROJECT) throw new Error('enumeration is not from the production Move project');
  const publishable = enumeration.rows.filter(r => r.publicationState === 'PUBLISHABLE');
  const supported = publishable.filter(r => r.moveClass !== 'HELD_OUT_OF_SERVICE' && r.moveClass !== 'HELD_UNSUPPORTED_CLASS');
  const eligible = supported.filter(r => r.moveClass === 'ELIGIBLE');
  const legal = r => r.fmcsaLegalName.trim();
  const groups = new Map();
  for (const r of eligible) { const k = legal(r).toLowerCase(); groups.set(k, [...(groups.get(k) ?? []), r]); }
  const wellFormed = r => USDOT.test(r.usdot) && SLUG.test(r.slug) && legal(r).length >= 2 && legal(r).length <= 300 && !/[\u0000-\u001f\u007f\\]/.test(legal(r));
  const verdict = r => {
    if (r.moveClass !== 'ELIGIBLE') return r.moveClass === 'RUNTIME_DISAGREES' ? 'MOVE_RUNTIME_DISAGREES_HOLD' : r.moveClass;
    if (!wellFormed(r)) return 'MISSING_REQUIRED_IDENTITY';
    // Every member of a colliding label group is held; no arbitrary winner. This
    // is a Move-side hold, not an Ask classification: Ask classes exist only
    // once the production reconciliation has run.
    if (groups.get(legal(r).toLowerCase()).length > 1) return 'MOVE_NAME_COLLISION_HOLD';
    return 'CANDIDATE';
  };
  const judged = supported.map(r => ({ ...r, legalName: legal(r), moveVerdict: verdict(r) }));
  const candidates = judged.filter(r => r.moveVerdict === 'CANDIDATE').sort((a, b) => Number(a.usdot) - Number(b.usdot));
  if (new Set(candidates.map(r => r.usdot)).size !== candidates.length || new Set(candidates.map(r => r.slug)).size !== candidates.length) throw new Error('candidate USDOT or slug repeats');
  // The same string the SQL recomputes from the loaded table.
  const canonical = candidates.map(r => `${r.usdot}|${r.slug}|${r.legalName}`).join('\n');
  const sha256 = createHash('sha256').update(canonical, 'utf8').digest('hex');
  const counts = {};
  for (const r of judged) counts[r.moveVerdict] = (counts[r.moveVerdict] ?? 0) + 1;
  return { enumeratedAt: enumeration.finishedAt, publishable: publishable.length, unsupported: publishable.length - supported.length, supported: supported.length, counts, judged, candidates, sha256 };
}

const q = value => "'" + value.replaceAll("'", "''") + "'";
const csv = value => /[",\n]/.test(value) ? '"' + value.replaceAll('"', '""') + '"' : value;

export function candidateSql(m) {
  const values = m.candidates.map(r => `(${q(r.usdot)},${q(r.slug)},${q(r.legalName)})`);
  const chunks = [];
  for (let i = 0; i < values.length; i += 500) chunks.push('insert into pg_temp.v23bulk_candidates(usdot,slug,legal_name) values\n' + values.slice(i, i + 500).join(',\n') + ';');
  return `-- GENERATED by scripts/release/mth-v2-exact-usdot-packet.mjs — do not edit by hand.
-- MY TRUSTHUB V2 PRODUCTION — MOVE EXACT-USDOT CANDIDATES (session-local, operator).
-- Source: production Move public.companies (${MOVE_PROJECT}), anonymous read,
-- enumerated ${m.enumeratedAt}. ${m.candidates.length} candidates. Manifest sha256
-- ${m.sha256}
-- Every row: publication_state PUBLISHABLE, not out of service, household-goods
-- carrier class, valid USDOT, exactly one Move company row for that USDOT.
-- This file writes ONLY a temporary table in the operator's own session. It
-- reads and writes no network or consumer row.
do $$ begin
  if current_setting('standard_conforming_strings') <> 'on' then raise exception 'standard_conforming_strings must be on'; end if;
  if to_regclass('pg_temp.v23bulk_candidates') is not null then raise exception 'Candidates already loaded in this session; use a fresh session'; end if;
end $$;
create temp table v23bulk_candidates(
  usdot text primary key check (usdot ~ '^[1-9][0-9]{0,8}$'),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{0,159}$'),
  legal_name text not null check (char_length(legal_name) between 2 and 300 and legal_name = btrim(legal_name))
) on commit preserve rows;
create unique index on pg_temp.v23bulk_candidates(lower(legal_name));
${chunks.join('\n')}
select set_config('v23bulk.manifest_sha256','${m.sha256}',false),
  set_config('v23bulk.manifest_rows','${m.candidates.length}',false),
  set_config('v23bulk.enumerated_at','${m.enumeratedAt}',false);
`;
}

export function evidenceCsv(m) {
  const head = 'move_verdict,usdot,slug,move_row_id,mc,legal_name,public_name,capabilities,sharing_row_ids';
  const lines = [...m.judged].sort((a, b) => a.moveVerdict.localeCompare(b.moveVerdict) || a.id.localeCompare(b.id))
    .map(r => [r.moveVerdict, r.usdot, r.slug, r.id, r.mc, r.legalName, r.name, r.capabilities.join(' '), (r.sharingRowIds ?? []).join(' ')].map(csv).join(','));
  return [head, ...lines].join('\n') + '\n';
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll('\\', '/').split('/').pop())) {
  const [input, out = 'docs/my-trusthub/v2/production'] = process.argv.slice(2);
  if (!input) { console.error('usage: mth-v2-exact-usdot-packet.mjs <move-candidates.json> [<out dir>]'); process.exit(2); }
  const m = buildManifest(JSON.parse(readFileSync(input, 'utf8')));
  writeFileSync(join(out, '11-move-exact-usdot-candidates.sql'), candidateSql(m));
  writeFileSync(join(out, '11-move-exact-usdot-evidence.csv'), evidenceCsv(m));
  console.log(JSON.stringify({ enumeratedAt: m.enumeratedAt, publishable: m.publishable, unsupported: m.unsupported, supported: m.supported, counts: m.counts, candidates: m.candidates.length, sha256: m.sha256 }, null, 1));
}
